#!/usr/bin/env python3
"""Generate leopardegl/gles_stubs.c: every GLES 2.0 + 3.0 entry point as an exported function that
resolves its implementation lazily through lgl_resolve() (leopardegl/gles.c).

  tools/gen-gles-stubs.py <gl.xml> <out.c>

Functions LeopardEGL implements itself (version strings, extension lists, shader prefixing) are left
out here; gles.c defines them. The registry is Khronos gl.xml (shipped in the libepoxy sources).
"""
import sys
import xml.etree.ElementTree as ET

HANDWRITTEN = {"glGetString", "glGetStringi", "glGetIntegerv", "glShaderSource", "glCompileShader", "glLinkProgram", "glReadPixels", "glDeleteTextures", "glTexImage2D", "glTexSubImage2D", "glTexStorage2D"}
FEATURES = {"GL_ES_VERSION_2_0", "GL_ES_VERSION_3_0"}


def text_of(elem):
    return "".join(elem.itertext()).strip()


def main():
    registry, out = sys.argv[1], sys.argv[2]
    root = ET.parse(registry).getroot()
    commands = {}
    for cmd in root.find("commands"):
        proto = cmd.find("proto")
        name = proto.find("name").text
        ret = text_of(proto)[: -len(name)].strip()
        params = []
        for p in cmd.findall("param"):
            pname = p.find("name").text
            params.append((text_of(p), pname))
        commands[name] = (ret, params)

    wanted = []
    for feature in root.findall("feature"):
        if feature.get("api") != "gles2" or feature.get("name") not in FEATURES:
            continue
        for req in feature.findall("require"):
            for c in req.findall("command"):
                n = c.get("name")
                if n not in wanted:
                    wanted.append(n)

    lines = [
        "/* Generated by tools/gen-gles-stubs.py from Khronos gl.xml: do not edit.\n * Copyright (c) 2026 Jordan Bettcher. SPDX-License-Identifier: MIT */",
        "#include <GLES3/gl3.h>",
        "#include \"gles_private.h\"",
        "",
    ]
    count = 0
    for name in sorted(wanted):
        if name in HANDWRITTEN:
            continue
        ret, params = commands[name]
        decl = ", ".join(t for t, _ in params) or "void"
        args = ", ".join(n for _, n in params)
        ptype = "%s (*)(%s)" % (ret, decl)
        call = "((%s)lgl_fn_)(%s)" % (ptype, args)
        check = "" if name == "glGetError" else "\n    if (lgl_debug_level) lgl_check_error(\"%s\");" % name
        # LEOPARD_GLES_DEBUG=4: print the call with its arguments before making it
        fmts, vals = [], []
        for t, n in params:
            if "*" in t:
                fmts.append("%p"); vals.append("(const void *)%s" % n)
            elif "float" in t.lower() or "double" in t.lower() or "clamp" in t.lower():
                fmts.append("%g"); vals.append("(double)%s" % n)
            elif "sync" in t.lower():
                fmts.append("%p"); vals.append("(const void *)%s" % n)
            else:
                fmts.append("0x%lx"); vals.append("(unsigned long)%s" % n)
        trace = "    if (lgl_debug_level >= 4) lgl_trace_call(\"%s(%s)\"%s);\n" % (
            name, ", ".join(fmts), "".join(", " + v for v in vals))
        if ret != "void":
            body = "%s lgl_ret_ = %s;%s\n    return lgl_ret_;" % (ret, call, check)
        else:
            body = "%s;%s" % (call, check)
        # Cache only a real implementation: the driver's entry points appear once it is loaded.
        lines.append("LGL_EXPORT %s GL_APIENTRY %s(%s)\n{\n    static void *lgl_cache_;\n    void *lgl_fn_ = lgl_cache_;\n"
                     "    if (!lgl_fn_ && !(lgl_fn_ = lgl_cache_ = lgl_resolve(\"%s\")))\n        lgl_fn_ = lgl_resolve_or_trap(\"%s\");\n"
                     "%s    %s\n}\n" % (ret, name, decl, name, name, trace, body))
        count += 1
    lines.append("/* %d entry points */" % count)
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("%d stubs -> %s" % (count, out))


if __name__ == "__main__":
    main()
